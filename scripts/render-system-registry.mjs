import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

import { validateRegistry } from "./system-registry-contract.mjs";


const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = resolve(scriptDir, "..");
const sourcePath = resolve(root, "system", "systems.json");
const outputPath = resolve(root, "system", "systems.js");
const homeOutputPath = resolve(root, "home", "src", "system-registry.ts");

const source = await readFile(sourcePath, "utf8");
const registry = JSON.parse(source);
validateRegistry(registry);
const normalized = `${JSON.stringify(registry, null, 2)}\n`;
const moduleSource = [
  "// Generated by scripts/render-system-registry.mjs. Do not edit.",
  `export const SYSTEM_REGISTRY_JSON = ${JSON.stringify(normalized)};`,
  "export const SYSTEM_REGISTRY = JSON.parse(SYSTEM_REGISTRY_JSON);",
  "export const SYSTEMS = SYSTEM_REGISTRY.systems;",
  "export const FEATURED_SYSTEMS = SYSTEMS.filter((system) => system.placement === \"featured\");",
  "export const CAPABILITY_DOMAINS = SYSTEM_REGISTRY.domains;",
  "export const EVIDENCE_STREAM = SYSTEMS.flatMap((system) => system.evidence.map((evidence) => ({ ...evidence, systemId: system.id }))).sort((left, right) => right.date.localeCompare(left.date));",
  "export function systemById(id) { return SYSTEMS.find((system) => system.id === id); }",
  "export function relatedSystems(id) { const system = systemById(id); return system ? system.related.map((relatedId) => systemById(relatedId)).filter(Boolean) : []; }",
  "",
].join("\n");
const homeModuleSource = [
  "// Generated by scripts/render-system-registry.mjs. Do not edit.",
  'export type EvidenceType = "source" | "release" | "test" | "report" | "demo" | "benchmark" | "paper" | "pull-request" | "public-receipt" | "code-permalink";',
  'export type EvidenceStatus = "verified" | "reported" | "unknown";',
  'export type SystemFamily = "platform" | "security" | "verification" | "infrastructure" | "graphics-retro" | "research-education";',
  "export type ArchitectureRole = string;",
  "export type EvidenceRecord = { id: string; type: EvidenceType; label: string; href: string; date: string; status: EvidenceStatus; summary: string };",
  "export type SystemRecord = { id: string; name: string; purpose: string; useCases: string[]; href: string; sourceHref: string | null; domains: string[]; family: SystemFamily; architectureRole: ArchitectureRole; audiences: string[]; deploymentContexts: string[]; maturity: string; placement: string; accessMode: string; entryCommand: string | null; verificationCommand: string | null; evidence: EvidenceRecord[]; limitations: string[]; boundary: string; inputs: string[]; outputs: string[]; dependencies: string[]; related: string[]; lastVerified: string; primaryDomain: string; productType: string; releaseState: string };",
  "export type CapabilityDomain = { id: string; label: string; summary: string };",
  "export type RelationshipPolicy = { relatedUsage: string; integrationClaims: string; hierarchyClaims: string };",
  "export type RelationRecord = { source: string; target: string; relation: string; status: string; evidenceIds: string[]; claimScope: string };",
  "type SystemRegistry = { schema: string; domains: CapabilityDomain[]; relationshipPolicy: RelationshipPolicy; relations: RelationRecord[]; systems: SystemRecord[] };",
  `export const SYSTEM_REGISTRY_JSON = ${JSON.stringify(normalized)};`,
  "export const SYSTEM_REGISTRY = JSON.parse(SYSTEM_REGISTRY_JSON) as SystemRegistry;",
  "export const SYSTEMS = SYSTEM_REGISTRY.systems;",
  'export const FEATURED_SYSTEMS = SYSTEMS.filter((system) => system.placement === "featured");',
  "export const CAPABILITY_DOMAINS = SYSTEM_REGISTRY.domains;",
  "export const EVIDENCE_STREAM = SYSTEMS.flatMap((system) => system.evidence.map((evidence) => ({ ...evidence, systemId: system.id }))).sort((left, right) => right.date.localeCompare(left.date));",
  "export function systemById(id: string) { return SYSTEMS.find((system) => system.id === id); }",
  "export function relatedSystems(id: string) { const system = systemById(id); return system ? system.related.map((relatedId: string) => systemById(relatedId)).filter(Boolean) : []; }",
  "",
].join("\n");

await writeFile(outputPath, moduleSource, "utf8");
await writeFile(homeOutputPath, homeModuleSource, "utf8");
console.log(`rendered ${outputPath} and ${homeOutputPath}`);
