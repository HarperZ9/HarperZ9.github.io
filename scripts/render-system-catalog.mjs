import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { validateRegistry } from "./system-registry-contract.mjs";


const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const registry = validateRegistry(JSON.parse(await readFile(resolve(root, "system", "systems.json"), "utf8")));
const domainById = new Map(registry.domains.map((domain) => [domain.id, domain]));

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function renderSecondaryDomains(system) {
  const secondary = system.domains.filter((domain) => domain !== system.primaryDomain);
  if (secondary.length === 0) return "";
  const labels = secondary.map((domain) => escapeHtml(domainById.get(domain)?.label ?? domain));
  return `<span class="catalog-secondary"><strong>Also relevant to</strong> ${labels.join(" · ")}</span>`;
}

function renderRecord(system) {
  const evidence = system.evidence[0];
  const evidenceMarkup = evidence
    ? `<span class="catalog-evidence"><strong>${escapeHtml(evidence.label)}</strong>: ${escapeHtml(evidence.summary)}</span>`
    : "";
  return [
    '<article class="index-row" role="listitem">',
    `<span class="index-term"><a href="${escapeHtml(system.href)}">${escapeHtml(system.name)}</a></span>`,
    '<span class="index-gloss">',
    `${escapeHtml(system.purpose)}`,
    renderSecondaryDomains(system),
    evidenceMarkup,
    `<small>${escapeHtml(system.productType)} · ${escapeHtml(system.releaseState)} · checked ${escapeHtml(system.lastVerified)}</small>`,
    "</span></article>",
  ].join("");
}

function renderDomain(domain) {
  const systems = registry.systems.filter((system) => system.primaryDomain === domain.id);
  return [
    `<section class="mv catalog-domain" id="domain-${escapeHtml(domain.id)}" aria-labelledby="domain-${escapeHtml(domain.id)}-h">`,
    `<h2 id="domain-${escapeHtml(domain.id)}-h">${escapeHtml(domain.label)} <span class="catalog-count">${systems.length} ${systems.length === 1 ? "record" : "records"}</span></h2>`,
    `<p class="body-text">${escapeHtml(domain.summary)}</p>`,
    `<div class="index" role="list">${systems.map(renderRecord).join("")}</div>`,
    "</section>",
  ].join("");
}

const domainLinks = registry.domains
  .map((domain) => `<a href="#domain-${escapeHtml(domain.id)}">${escapeHtml(domain.label)}</a>`)
  .join("");

