const TWO40 = 1n << 40n;
const TWO80 = 1n << 80n;

// floor(a / b) for BigInt a and b > 0 (BigInt division truncates toward zero).
function floorDivBig(a, b) {
  const q = a / b;
  return (a % b !== 0n && a < 0n) ? q - 1n : q;
}

// Floor cube root of a non-negative BigInt, by Newton steps from a power-of-two upper bound.
export function icbrtFloor(n) {
  if (n < 0n) throw new Error("icbrtFloor: negative input");
  if (n < 2n) return n;
  let x = 1n << BigInt(Math.ceil(n.toString(2).length / 3));
  for (;;) {
    const y = (2n * x + n / (x * x)) / 3n;
    if (y >= x) break;
    x = y;
  }
  while (x * x * x > n) x -= 1n;
  while ((x + 1n) * (x + 1n) * (x + 1n) <= n) x += 1n;
  return x;
}

// The integer nearest cbrt(num / den) * 2^40 for num >= 0 and den > 0.
function cbrtRationalQ40(num, den) {
  const scaled = num * (1n << 120n);
  const f = icbrtFloor(scaled / den);
  const t = 2n * f + 1n;
  return 8n * scaled >= t * t * t * den ? f + 1n : f;
}

function fixed9(numQ80) {
  const v = floorDivBig(numQ80 * 1000000000n + (TWO80 >> 1n), TWO80);
  const neg = v < 0n, a = neg ? -v : v;
  const s = a.toString().padStart(10, "0");
  return (neg ? "-" : "") + s.slice(0, -9) + "." + s.slice(-9);
}

// OKLab of the mean linear colour of the pixels for which keep(i) is true (all pixels when keep is null).
// px: RGBA (or ch-channel) sRGB bytes. Returns { L, a, b } as 9-decimal strings, or null when no pixel
// is kept.
export function oklabMeanExact(px, w, h, ch = 4, keep = null) {
  let r = 0n, g = 0n, b = 0n, count = 0n;
  for (let i = 0; i < w * h; i++) {
    if (keep && !keep(i)) continue;
    const o = i * ch;
    r += LIN_Q40[px[o]]; g += LIN_Q40[px[o + 1]]; b += LIN_Q40[px[o + 2]]; count += 1n;
  }
  if (count === 0n) return null;
  const den = count * TWO80; // mean linear = sum / (count * 2^40); LMS = M1_Q40 . sum / (count * 2^80)
  const lms = M1_Q40.map((row) => {
    const v = row[0] * r + row[1] * g + row[2] * b;
    return cbrtRationalQ40(v > 0n ? v : 0n, den);
  });
  const out = M2_Q40.map((row) => row[0] * lms[0] + row[1] * lms[1] + row[2] * lms[2]);
  return { L: fixed9(out[0]), a: fixed9(out[1]), b: fixed9(out[2]) };
}
