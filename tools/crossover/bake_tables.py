"""Bake the tables the crossover renderer reads, from the same physics the checks score.

python tools/crossover/bake_tables.py

Writes world/site/crossover/tables.js:
- BINS: 16 wavelength bins, 400 to 700 nm;
- XYZ: per-bin weights of the CIE 1931 2 deg observer under D65, scaled so a perfect white gives Y = 1;
- PAPER, INKS: the paper's body reflectance and each ink's absorbance per bin, from the overprint model
  (spectra recovered from the Olivetti "De A a Z" sheet, as a scan sees them); F0 = 0.04 for the glass surface;
and world/site/crossover/mie.png: the Lorenz-Mie phase function of a water droplet (m = 1.333) for 256
size parameters x from 0.1 to 60 (log spaced, rows) and 361 scattering angles 0 to 180 deg (columns),
stored as log10(p / max p) over six decades in 8 bits.

Checks printed on every run (the bake fails if one fails):
- Mie against Bohren and Huffman's BHMIE sample (m = 1.55, x = 5.2128): Qext 3.10543, Qback 2.92534;
- the Rayleigh limit: p(90) / p(0) = 0.5 for x = 0.01;
- 16-bin colour against the 5 nm integral for paper and every ink, CIEDE2000 under 1.
"""
import json
import pathlib
import subprocess
import sys

import numpy as np
import colour
import miepython as mp
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "world/site/crossover"
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import overprint_model as om  # noqa: E402

NB = 16


def check(name, ok, detail):
    print(("ok   " if ok else "FAIL ") + name + ": " + detail)
    if not ok:
        raise SystemExit(1)


def mie_checks():
    x = 2 * np.pi * 0.525 / 0.6328
    qext, qsca, qback, g = mp.efficiencies_mx(1.55, x)
    check("BHMIE sample", abs(qext - 3.10543) < 1e-4 and abs(qback - 2.92534) < 1e-4, f"Qext {qext:.5f}, Qback {qback:.5f}")
    i = mp.i_unpolarized(1.33, 0.01, np.cos(np.radians([0.0, 90.0])), norm="one")
    check("Rayleigh limit", abs(i[1] / i[0] - 0.5) < 1e-3, f"p(90)/p(0) = {i[1] / i[0]:.4f}")


def mie_lut():
    xs = np.geomspace(0.1, 60, 256)
    th = np.linspace(0, 180, 361)
    mu = np.cos(np.radians(th))
    img = np.zeros((len(xs), len(th)), np.uint8)
    for r, x in enumerate(xs):
        p = mp.i_unpolarized(1.333, x, mu, norm="one")
        lg = np.log10(np.maximum(p / p.max(), 1e-6))
        img[r] = np.round((lg + 6) / 6 * 255).astype(np.uint8)
    Image.fromarray(img, "L").save(OUT / "mie.png", optimize=True)
    return xs[0], xs[-1], len(xs), len(th)


def colour_tables():
    edges = np.linspace(400, 700, NB + 1)
    mids = (edges[:-1] + edges[1:]) / 2
    wl, cm, ill = om.WL, om.CMFS.values, om.D65.values
    w = np.zeros((NB, 3))
    for i, (lo, hi) in enumerate(zip(edges[:-1], edges[1:])):
        sel = (wl >= lo) & (wl < hi)
        w[i] = (cm[sel] * ill[sel, None]).sum(0)
    w /= w[:, 1].sum()
    band = lambda r: np.array([r[(wl >= lo) & (wl < hi)].mean() for lo, hi in zip(edges[:-1], edges[1:])])
    rs = 0.0  # a scan or copy-stand view sees no mirror reflection on flat print; the renderer adds Fresnel itself
    paper = om.body(om.S["paper"], rs)
    inks = {k: -np.log(np.clip(om.body(om.S[k], rs) / paper, 1e-5, 1)) for k in om.INKS if k != "paper"}
    # parity: the 16-bin sum against the 5 nm integral, for paper and each ink on paper
    to_hex = lambda xyz: "#" + "".join(f"{int(round(v * 255)):02x}" for v in np.clip(colour.XYZ_to_sRGB(xyz), 0, 1))
    worst = 0.0
    for k in ["paper"] + list(inks):
        r5 = rs + (1 - rs) * (paper * (np.exp(-inks[k]) if k != "paper" else 1))
        rb = band(r5)
        e = om.scores(to_hex(rb @ w), om.refl_to_hex(r5))[1]
        worst = max(worst, e)
    check("16 bins against 5 nm", worst < 1.0, f"worst CIEDE2000 {worst:.2f}")
    xyz2rgb = colour.RGB_COLOURSPACES["sRGB"].matrix_XYZ_to_RGB
    return {"BINS": mids.round(2).tolist(), "XYZ": w.round(6).tolist(), "XYZ_TO_RGB": np.asarray(xyz2rgb).round(6).tolist(),
            "F0": om.F0, "PAPER": band(paper).round(5).tolist(), "INKS": {k: band(v).round(4).tolist() for k, v in inks.items()}}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    mie_checks()
    x0, x1, nx, nt = mie_lut()
    t = colour_tables()
    t["MIE"] = {"src": "mie.png", "x0": x0, "x1": x1, "nx": nx, "nt": nt, "decades": 6, "m": 1.333}
    head = "// Generated by tools/crossover/bake_tables.py; do not edit. Colour: CIE 1931 2 deg under D65.\n"
    body = "".join(f"export const {k} = {json.dumps(v)};\n" for k, v in t.items())
    (OUT / "tables.js").write_text(head + body, encoding="utf8")
    print("wrote", OUT / "tables.js", "and", OUT / "mie.png")


if __name__ == "__main__":
    main()
