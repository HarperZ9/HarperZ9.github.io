export const GLYPHS = Object.freeze(Object.keys(G));
export const bitmap = (ch) => G[ch] ?? G[String(ch).toUpperCase()] ?? null;

// Width of a string in px at cell size px (5 cells + 1 cell tracking per glyph, no trailing space).
export const measure = (text, px) => Math.max(0, String(text).length * 6 - 1) * px;

// Draw text with its top-left at (x, y), or aligned 'right' / 'centre' to x. Unknown characters throw,
// so a typo never prints a blank where a value belongs.
export function text(S, str, x, y, { px = 4, ink = '#f4f1ea', align = 'left' } = {}) {
  const s = String(str), I = colour(ink), W = measure(s, px);
  // whole-pixel origin: cells on fractional positions overlap at partial coverage and leave seams
  let cx = Math.round(align === 'right' ? x - W : align === 'centre' ? x - W / 2 : x); y = Math.round(y);
  for (const ch of s) {
    const b = bitmap(ch); if (!b) throw new Error(`numerals: no glyph for "${ch}"`);
    for (let j = 0; j < 7; j++) for (let i = 0; i < 5; i++) if (b[j][i] === '#') cell(S, cx + i * px, y + j * px, px, I);
    cx += 6 * px;
  }
  return W;
}

// A ruled readout table: rows of [label, value], hairlines between rows, the labels left, values right.
export function readout(S, rows, x, y, { px = 4, ink = '#f4f1ea', rule = '#8a867c', colW = null, gap = 3 } = {}) {
  const lh = 7 * px + 2 * gap * px / 2 + px * 2, Rr = colour(rule), lw = Math.max(1, px / 3);
  const w1 = colW ?? Math.max(...rows.map((r) => measure(r[0], px))) + 6 * px, w2 = Math.max(...rows.map((r) => measure(r[1], px)));
  rows.forEach(([a, b], k) => {
    const ty = y + k * lh + px * 2;
    text(S, a, x, ty, { px, ink }); text(S, b, x + w1 + w2, ty, { px, ink, align: 'right' });
    line(S, x, y + (k + 1) * lh, x + w1 + w2, y + (k + 1) * lh, lw, Rr);
  });
  line(S, x, y, x + w1 + w2, y, lw, Rr);
  return { w: w1 + w2, h: rows.length * lh };
}
