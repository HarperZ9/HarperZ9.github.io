"""Contracts for the generated v4 product overview route."""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "overview.html"
SYSTEMS = ROOT / "system" / "systems.json"


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def registry() -> dict[str, object]:
    return json.loads(read(SYSTEMS))


def systems_by_id() -> dict[str, dict]:
    return {record["id"]: record for record in registry()["systems"]}


def section(page: str, section_id: str) -> str:
    match = re.search(
        rf'<section\b[^>]*\bid="{re.escape(section_id)}"[^>]*>.*?</section>',
        page,
        re.DOTALL,
    )
    assert match, section_id
    return match.group(0)


def test_engines_page_is_the_generated_product_overview() -> None:
    page = read(PAGE)
    payload = registry()
    public_records = [
        record for record in payload["systems"] if record["maturity"] != "controlled-private"
    ]

    assert "<!-- Generated by scripts/render-system-pages.mjs. Do not edit. -->" in page
    assert "Zain Dana Harper" in page
    assert "Zentropy Labs" in page
    assert page.index("Zentropy Labs") < page.index("Flywheel")
    assert '<title>Products · Zentropy Labs</title>' in page
    assert '<body class="inner-clean frame-compact">' in page
    assert 'href="system/system.css?v=20260902-creative-chassis"' in page
    assert 'src="system/nav.js?v=20260902-creative-chassis"' in page
    assert "Products, grouped by primary domain." in page
    assert f"{len(public_records)} public product records across {len(payload['domains'])} domains." in page
    assert "Short map, detailed record elsewhere" in page
    assert 'href="catalog.html">evidence registry</a>' in page

    for domain in payload["domains"]:
        assert f'id="overview-{domain["id"]}"' in page
        assert f'href="#overview-{domain["id"]}"' in page

    for stale in (
        "Project Telos",
        "The fourteen engines",
        "Built as a field guide, not a funnel",
        'class="engine-rail"',
        'class="eyebrow"',
        'class="scenarios',
        'class="scenario',
    ):
        assert stale not in page


