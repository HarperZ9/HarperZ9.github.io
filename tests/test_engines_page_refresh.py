def test_engines_page_release_facts_match_the_system_registry() -> None:
    page = read(PAGE)
    systems = systems_by_id()

    for system_id in (
        "flywheel",
        "telos",
        "index",
        "gather",
        "forum",
        "crucible",
        "relay",
        "plexus",
        "mneme",
        "studio-engine",
        "retro-engine",
        "engine-revival",
        "brender-archival",
    ):
        record = systems[system_id]
        link = f'<a href="{record["href"]}">{record["name"]}</a>'
        primary = section(page, f'overview-{record["primaryDomain"]}')

        assert page.count(link) == 1, system_id
        assert link in primary, system_id
        assert record["productType"] in primary, system_id
        assert f'{record["maturity"]} · {record["releaseState"]}' in primary, system_id


def test_engines_page_keeps_readable_generated_overview_styles() -> None:
    page = read(PAGE)
    style = re.search(r"<style>(?P<body>.*?)</style>", page, re.DOTALL)
    assert style
    css = style.group("body")

    for selector in (
        ".system-hero",
        ".domain-nav",
        ".catalog-domain",
        ".catalog-count",
        ".system-family-nav",
    ):
        assert selector in css

    assert "@media(max-width:720px)" in css
    assert not re.search(r"font-size:\s*clamp\([^)]*,\s*[^,]+,\s*(?:[7-9]|\d{2,})rem", css)
